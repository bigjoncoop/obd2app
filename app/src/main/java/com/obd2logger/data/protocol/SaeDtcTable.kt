object SaeDtcTable {

    fun lookup(code: String): String {
        val normalized = code.trim().uppercase()
        CODES[normalized]?.let { return it }
        return fallbackDescription(normalized)
    }

    private fun fallbackDescription(code: String): String {
        if (code.length < 2) return "Unknown Diagnostic Code"
        val prefix = code[0]
        val second = code[1]
        val system = when (prefix) {
            'P' -> "Powertrain"
            'C' -> "Chassis"
            'B' -> "Body"
            'U' -> "Network"
            else -> "OBD-II"
        }
        return when (second) {
            '0', '2' -> "Generic $system Code"
            '1', '3' -> "Manufacturer-Specific $system Code"
            else -> "$system Diagnostic Code"
        }
    }

